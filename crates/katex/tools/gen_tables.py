#!/usr/bin/env python3
"""Generate the constant tables in src/generated/ from data/*.json.

Not part of the build: run it by hand after changing data/ or the accent
table, and commit the output.

    python3 -I crates/katex/tools/gen_tables.py

Uses only the Python standard library. The Unicode symbol table depends on
NFC normalization (unicodedata); its output equals KaTeX's
unicodeSymbols.js.
"""

import json
import os
import re
import sys
import unicodedata
from decimal import Decimal

CRATE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(CRATE, "src", "generated")
HEADER = "// Generated by tools/gen_tables.py from {}. Do not edit.\n\n"


def rust_float(v):
    """Formats a float as Rust's `Display` does (shortest round trip, no
    exponent)."""
    r = repr(float(v))
    if "e" in r or "E" in r:
        r = format(Decimal(r), "f")
    return r


def snake(name):
    out = ""
    for i, ch in enumerate(name):
        if ch.isupper() and i > 0:
            out += "_"
        out += ch.lower()
    return out


def escape_as_unicode(s):
    return "".join(
        c if c.isascii() and not (ord(c) < 0x20 or ord(c) == 0x7F) else "\\u{%x}" % ord(c)
        for c in s
    )


def json_number(v):
    """Formats a JSON number as serde_json's `Value::to_string` does, or
    `{:.1}` for integers."""
    if isinstance(v, int):
        return "%d.0" % v
    return rust_float(v)


def sigmas_and_xis():
    data = json.load(open(os.path.join(CRATE, "data", "sigmas_and_xis.json")))
    table, docs = data["sigmasAndXis"], data["fieldDocs"]
    # serde_json's map (the original generator) iterated keys in sorted order.
    keys = sorted(table)
    fields = ""
    for key in keys:
        if key in docs:
            fields += "    /// %s\n" % docs[key]
        fields += "    pub %s: f64,\n" % snake(key)
    fields += "    /// CSS em per mu\n    pub css_em_per_mu: f64,\n"
    consts = ""
    for index in range(3):
        consts += "    FontMetrics {\n"
        for key in keys:
            values = table[key]
            if isinstance(values, list) and index < len(values):
                consts += "        %s: %s,\n" % (snake(key), json_number(values[index]))
        consts += "        css_em_per_mu: %s,\n" % rust_float(table["quad"][index] / 18.0)
        consts += "    },\n"
    return (
        "// Auto-generated from KaTeX/src/fontMetrics.js\n"
        "// Do not edit manually\n\n"
        "#[derive(Debug, Clone)]\n"
        "/// Font metrics for a specific style size (text, script, scriptscript)\n"
        "pub struct FontMetrics {\n" + fields + "}\n\n"
        "/// Constant font metrics for textstyle, scriptstyle, and scriptscriptstyle\n"
        "pub const FONT_METRICS: [FontMetrics; 3] = [\n" + consts + "];\n"
    )


def font_metrics():
    data = json.load(open(os.path.join(CRATE, "data", "font_metrics_data.json")))
    out, index = "", ""
    for family in sorted(data, key=lambda s: s.encode()):
        name = family.replace("-", "_").replace(".", "_").upper()
        index += '    ("%s", &%s_METRICS),\n' % (family, name)
        entries = []
        for code, values in data[family].items():
            text = ", ".join(
                ("%s" % rust_float(v) if float(v) != int(v) else "%d.0" % int(v)) for v in values
            )
            entries.append((int(code), text))
        entries.sort()
        out += "/// Font metrics for the %s font family\n" % family
        out += (
            "#[allow(clippy::approx_constant)]\n"
            "pub const %s_METRICS: Map<u32, CharacterMetrics> = U32Map::new(&[\n" % name
        )
        for code, text in entries:
            out += "    (%d, CharacterMetrics::new(%s)),\n" % (code, text)
        out += "]);\n\n"
    out += "/// Mapping of font family names to their corresponding metrics maps\n"
    out += (
        "pub const FONT_METRICS_INDEX: Map<&'static str, &'static Map<u32, CharacterMetrics>> "
        "= StrMap::new(&[\n" + index + "]);\n"
    )
    return out


def accents():
    """The keys of UNICODE_ACCENTS, in key order."""
    src = open(os.path.join(CRATE, "src", "unicode", "unicode_accents.rs")).read()
    keys = [chr(int(h, 16)) for h in re.findall(r"^\s*\(?\s*'\\u\{([0-9a-fA-F]+)\}',", src, re.M)]
    if not keys:
        sys.exit("no accents found in unicode_accents.rs")
    return sorted(keys)


def unicode_symbols():
    letters = (
        "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ"
        "\u03b1\u03b2\u03b3\u03b4\u03b5\u03f5\u03b6\u03b7\u03b8\u03d1\u03b9\u03ba\u03bb\u03bc"
        "\u03bd\u03be\u03bf\u03c0\u03d6\u03c1\u03f1\u03c2\u03c3\u03c4\u03c5\u03c6\u03d5\u03c7"
        "\u03c8\u03c9\u0393\u0394\u0398\u039b\u039e\u03a0\u03a3\u03a5\u03a6\u03a8\u03a9"
    )
    marks = accents()
    table = {}

    def add(combined):
        normalized = unicodedata.normalize("NFC", combined)
        if len(normalized) == 1 and normalized not in table:
            table[normalized] = escape_as_unicode(combined)

    for letter in letters:
        for accent in marks:
            add(letter + accent)
            for accent2 in marks:
                if accent != accent2:
                    add(letter + accent2 + accent)
    out = (
        "/// Mapping of normalized Unicode symbols to their component parts\n"
        "/// Unicode symbols map for Modifier tone letters\n"
        "#[allow(clippy::non_ascii_literal)]\n"
        "pub const UNICODE_SYMBOLS: Map<char, &str> = CharMap::new(&[\n"
    )
    for symbol in sorted(table):
        out += "    ('%s', \"%s\"),\n" % (escape_as_unicode(symbol), table[symbol])
    return out + "]);\n"


def convert_unicode_escapes(s):
    """Rewrites `\\uXXXX` and `\\u{X}` in symbol names as Rust `\\u{X}`
    escapes."""
    return re.sub(
        r"\\u(\{([0-9a-fA-F]+)\}|([0-9a-fA-F]{4}))",
        lambda m: "\\u{%s}" % (m.group(2) or m.group(3)),
        s,
    )


def unescape_literal(literal):
    out, i = "", 0
    while i < len(literal):
        c = literal[i]
        if c != "\\":
            out += c
            i += 1
            continue
        n = literal[i + 1]
        if n == "u":
            j = literal.index("}", i)
            out += chr(int(literal[i + 3 : j], 16))
            i = j + 1
            continue
        out += {"\\": "\\", '"': '"', "'": "'", "n": "\n", "t": "\t"}[n]
        i += 2
    return out


FONTS = {"main": "Font::Main", "ams": "Font::Ams"}
GROUPS = {
    "bin": "Group::Atom(Atom::Bin)",
    "close": "Group::Atom(Atom::Close)",
    "inner": "Group::Atom(Atom::Inner)",
    "open": "Group::Atom(Atom::Open)",
    "punct": "Group::Atom(Atom::Punct)",
    "rel": "Group::Atom(Atom::Rel)",
    "accent": "Group::NonAtom(NonAtom::AccentToken)",
    "accent-token": "Group::NonAtom(NonAtom::AccentToken)",
    "mathord": "Group::NonAtom(NonAtom::MathOrd)",
    "op": "Group::NonAtom(NonAtom::OpToken)",
    "op-token": "Group::NonAtom(NonAtom::OpToken)",
    "spacing": "Group::NonAtom(NonAtom::Spacing)",
    "textord": "Group::NonAtom(NonAtom::TextOrd)",
}


def symbol_table(symbols, variant):
    entries = {}
    for s in symbols:
        replace = s.get("replace")
        replace_value = (
            "Some('%s')" % convert_unicode_escapes(replace) if replace else "None"
        )
        info = (
            "CharInfo {\n            font: %s,\n            group: %s,\n"
            "            replace: %s,\n        }"
            % (FONTS[s["font"]], GROUPS[s["group"]], replace_value)
        )
        names = [s["name"]]
        if s["acceptUnicodeChar"] and replace is not None:
            names.append(replace)
        for name in names:
            literal = convert_unicode_escapes(name)
            key = unescape_literal(literal).encode()
            if key in entries and entries[key][1] != info:
                sys.exit("conflicting definitions of %r" % name)
            entries[key] = (literal, info)
    out = "const %s_MAP: Map<&str, CharInfo> = StrMap::new(&[\n" % variant
    for key in sorted(entries):
        literal, info = entries[key]
        out += '    (\n        "%s",\n        %s,\n    ),\n' % (literal, info)
    return out + "]);\n\n"


def symbols():
    data = json.load(open(os.path.join(CRATE, "data", "symbols.json")))
    math = [s for s in data if s["mode"] == "math"]
    text = [s for s in data if s["mode"] != "math"]
    return (
        "// Auto-generated file - do not edit manually\n"
        "// Generated from data/symbols.json\n\n"
        "/// Populate math symbols from JSON data\n"
        + symbol_table(math, "POPULATE_MATH_SYMBOLS")
        + "/// Populate text symbols from JSON data\n"
        + symbol_table(text, "POPULATE_TEXT_SYMBOLS")
    )


# the groups in the order of the packed symbol table (src/symbols/packed.rs reads them back by this index)
PACKED_GROUPS = ["bin", "close", "inner", "open", "punct", "rel", "accent-token", "mathord", "op-token", "spacing", "textord"]
PACKED_GROUP_OF = {"accent": "accent-token", "op": "op-token"}


def varint(n):
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def packed_symbols():
    """The symbol tables as the Rust side reads them with the `packed-symbols` feature (src/symbols/packed.rs): for the math table and then the text
    table, the number of entries n, then the n names (length and bytes), n bytes (bit 7: the entry's `replace` character is also a key, bit 6: font
    ams, low bits: the group's index in PACKED_GROUPS), n varints (the replace character as a zig-zag difference from the previous entry's, 0 for none). The entries are
    those of symbols.json, in the order of their replace characters; the table of every key (names and the characters of `acceptUnicodeChar`) is what `symbols()` writes: this checks it."""
    data = json.load(open(os.path.join(CRATE, "data", "symbols.json")))
    blob = b""
    for modes, variant in ((["math"], "math"), (None, "text")):
        syms = [s for s in data if (s["mode"] == "math") == (variant == "math")]
        base = {}
        for s in syms:
            key = unescape_literal(convert_unicode_escapes(s["name"]))
            rep = s.get("replace")
            rch = unescape_literal(convert_unicode_escapes(rep)) if rep else None
            assert rch is None or len(rch) == 1
            entry = (s["font"], PACKED_GROUP_OF.get(s["group"], s["group"]), rch, bool(s["acceptUnicodeChar"] and rep is not None))
            if key in base and base[key] != entry:
                sys.exit("conflicting definitions of %r" % key)
            base[key] = entry
        # in the order of the replaced character, which is also what compresses best (the characters are written as differences)
        names = sorted(base, key=lambda k: (ord(base[k][2]) if base[k][2] else 0, k.encode()))
        blob += varint(len(names))
        for k in names:
            b = k.encode()
            blob += varint(len(b)) + b
        for k in names:
            f, g, r, acc = base[k]
            blob += bytes([(0x80 if acc else 0) | (0x40 if f == "ams" else 0) | PACKED_GROUPS.index(g)])
        prev = 0
        for k in names:
            r = base[k][2]
            c = ord(r) if r else 0
            d = c - prev
            blob += varint((d << 1) if d >= 0 else ((-d << 1) - 1))
            prev = c
        # check against the table that symbol_table writes
        full = {}
        for k in names:
            f, g, r, acc = base[k]
            for key in [k] + ([r] if acc else []):
                info = (f, g, r)
                if key in full and full[key] != info:
                    sys.exit("conflicting definitions of %r" % key)
                full[key] = info
        ref = {}
        for s in syms:
            rep = s.get("replace")
            for name in [s["name"]] + ([rep] if s["acceptUnicodeChar"] and rep is not None else []):
                key = unescape_literal(convert_unicode_escapes(name))
                rch = unescape_literal(convert_unicode_escapes(rep)) if rep else None
                ref[key] = (s["font"], PACKED_GROUP_OF.get(s["group"], s["group"]), rch)
        if full != ref:
            sys.exit("the packed %s symbols are not the table of symbols()" % variant)
    return blob


def main():
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "symbols_packed.bin"), "wb") as f:
        f.write(packed_symbols())
    for name, source, text in [
        ("sigmas_and_xis.rs", "data/sigmas_and_xis.json", sigmas_and_xis()),
        ("font_metrics_data.rs", "data/font_metrics_data.json", font_metrics()),
        ("unicode_symbols.rs", "src/unicode/unicode_accents.rs", unicode_symbols()),
        ("symbols_data.rs", "data/symbols.json", symbols()),
    ]:
        with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
            f.write(HEADER.format(source) + text)


if __name__ == "__main__":
    main()
